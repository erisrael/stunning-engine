export const LETTER_GROUPS = [...new Set(LETTER_LIBRARY.map((t) => t.group))];

// {{field}} replaced from the values (unknown fields stay visible so a gap is noticed).
export function fillLetter(text: string, values: Record<string, string | undefined | null>) {
  return text.replace(/\{\{\s*([a-z0-9_]{1,40})\s*\}\}/gi, (m, k: string) => {
    const v = values[k.toLowerCase()];
    return v == null || v === "" ? m : String(v);
  });
}

// The fields a template still needs (none of the standard ones).
export const STANDARD_LETTER_FIELDS = ["recipient_name", "recipient_title", "recipient_company", "recipient_address", "company_name", "company_tin", "company_address", "issue_date", "document_number", "signatory_name", "signatory_position", "subject"];
export function missingFields(t: LetterTemplate, values: Record<string, string | undefined>) {
  return t.fields.filter((f) => !values[f.key]?.trim());
}

